import { mkdir, unlink, writeFile } from 'fs/promises';
import { join, resolve } from 'path';
import {
  DeleteObjectCommand,
  PutObjectCommand,
  S3Client,
} from '@aws-sdk/client-s3';
import type { StorageConfig } from '../common/env';

/**
 * Where uploaded files live.
 * - LocalDiskStorage: development, or hosts with a persistent volume
 *   (docker-compose.prod.yml mounts one). Files are served by the API at /uploads/<key>.
 * - S3Storage: any S3-compatible object store (Cloudflare R2, AWS S3, MinIO). Files are
 *   served from the bucket's public URL, so they survive redeploys on hosts with
 *   ephemeral disks (e.g. Render's free plan).
 */
export interface StorageAdapter {
  /** Stores the bytes under a server-generated key; returns the URL/path stored on the record. */
  save(key: string, data: Buffer, contentType: string): Promise<string>;
  /** Removes a file previously returned by save(). Unknown or foreign URLs are ignored. */
  remove(storedUrl: string): Promise<void>;
}

export const STORAGE_ADAPTER = Symbol('STORAGE_ADAPTER');

/** Keys are generated by the server (UUID + extension); anything else is rejected. */
export const STORAGE_KEY = /^[a-z0-9-]+\.(jpg|png|webp)$/;

export class LocalDiskStorage implements StorageAdapter {
  private readonly root: string;

  constructor(dir: string) {
    this.root = resolve(dir);
  }

  async save(key: string, data: Buffer): Promise<string> {
    if (!STORAGE_KEY.test(key)) throw new Error('Invalid storage key');
    await mkdir(this.root, { recursive: true });
    await writeFile(join(this.root, key), data, { flag: 'wx' });
    return `/uploads/${key}`;
  }

  async remove(storedUrl: string): Promise<void> {
    const key = storedUrl.replace(/^\/uploads\//, '');
    if (!STORAGE_KEY.test(key)) return;
    await unlink(join(this.root, key)).catch(() => undefined);
  }
}

const OBJECT_PREFIX = 'uploads/';

export class S3Storage implements StorageAdapter {
  private readonly client: S3Client;

  constructor(
    private readonly cfg: Extract<StorageConfig, { provider: 's3' }>,
    client?: S3Client,
  ) {
    this.client =
      client ??
      new S3Client({
        region: cfg.region,
        endpoint: cfg.endpoint ?? undefined,
        forcePathStyle: cfg.forcePathStyle,
        credentials: {
          accessKeyId: cfg.accessKeyId,
          secretAccessKey: cfg.secretAccessKey,
        },
      });
  }

  async save(key: string, data: Buffer, contentType: string): Promise<string> {
    if (!STORAGE_KEY.test(key)) throw new Error('Invalid storage key');
    await this.client.send(
      new PutObjectCommand({
        Bucket: this.cfg.bucket,
        Key: `${OBJECT_PREFIX}${key}`,
        Body: data,
        ContentType: contentType,
        // Keys are random and never reused, so the object can be cached indefinitely.
        CacheControl: 'public, max-age=31536000, immutable',
      }),
    );
    return `${this.cfg.publicUrl}/${OBJECT_PREFIX}${key}`;
  }

  async remove(storedUrl: string): Promise<void> {
    const prefix = `${this.cfg.publicUrl}/${OBJECT_PREFIX}`;
    if (!storedUrl.startsWith(prefix)) return;
    const key = storedUrl.slice(prefix.length);
    if (!STORAGE_KEY.test(key)) return;
    await this.client
      .send(
        new DeleteObjectCommand({
          Bucket: this.cfg.bucket,
          Key: `${OBJECT_PREFIX}${key}`,
        }),
      )
      .catch(() => undefined);
  }
}

export function createStorage(
  cfg: StorageConfig,
  uploadDir: string,
): StorageAdapter {
  return cfg.provider === 's3'
    ? new S3Storage(cfg)
    : new LocalDiskStorage(uploadDir);
}
