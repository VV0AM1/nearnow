import { S3Storage } from '../src/uploads/storage';
import { UploadsService } from '../src/uploads/uploads.service';
import { tinyPng } from './fixtures/images';

/**
 * Exercises the S3 adapter against the S3Mock container from docker-compose.yml
 * (`docker compose up -d s3mock`). Same code path as Cloudflare R2 / AWS S3.
 */
const ENDPOINT = process.env.E2E_S3_ENDPOINT || 'http://localhost:9090';
const BUCKET = 'nearnow-dev';

describe('S3 object storage (S3Mock)', () => {
  const storage = new S3Storage({
    provider: 's3',
    endpoint: ENDPOINT,
    region: 'us-east-1',
    bucket: BUCKET,
    accessKeyId: 'test',
    secretAccessKey: 'test',
    publicUrl: `${ENDPOINT}/${BUCKET}`,
    forcePathStyle: true,
  });
  const uploads = new UploadsService(storage);

  beforeAll(async () => {
    const res = await fetch(`${ENDPOINT}/`).catch(() => null);
    if (!res)
      throw new Error(
        `S3Mock is not reachable at ${ENDPOINT}. Run: docker compose up -d s3mock`,
      );
  });

  it('stores a sanitised image under a random key and serves it from the public URL', async () => {
    const url = await uploads.storeImage({
      buffer: tinyPng(),
    } as Express.Multer.File);
    expect(url).toMatch(
      new RegExp(`^${ENDPOINT}/${BUCKET}/uploads/[0-9a-f-]{36}\\.png$`),
    );

    const res = await fetch(url);
    expect(res.status).toBe(200);
    expect(res.headers.get('content-type')).toBe('image/png');
    const body = Buffer.from(await res.arrayBuffer());
    expect(body.includes(Buffer.from('GPS'))).toBe(false); // metadata stripped before upload
    expect(body.includes(Buffer.from('IDAT'))).toBe(true);
  });

  it('deletes its own objects and ignores URLs it does not own', async () => {
    const url = await uploads.storeImage({
      buffer: tinyPng(false),
    } as Express.Multer.File);
    await uploads.remove('https://lh3.googleusercontent.com/a/profile-photo');
    await uploads.remove(`${ENDPOINT}/${BUCKET}/uploads/../../etc/passwd`);
    expect((await fetch(url)).status).toBe(200);

    await uploads.remove(url);
    expect((await fetch(url)).status).toBe(404);
  });

  it('rejects keys that were not generated by the server', async () => {
    await expect(
      storage.save('../escape.png', Buffer.from('x'), 'image/png'),
    ).rejects.toThrow('Invalid storage key');
  });
});
